/* =========================================
   LOCAL STORAGE
========================================= */

let cart =
    JSON.parse(
        localStorage.getItem(
            "parisaCart"
        )
    ) || [];


let favorites =
    JSON.parse(
        localStorage.getItem(
            "parisaFavorites"
        )
    ) || [];



/* =========================================
   ELEMENTS
========================================= */

const artGrid =
    document.getElementById(
        "art-grid"
    );


const cartCount =
    document.getElementById(
        "cart-count"
    );



/* =========================================
   PRICE FORMAT
========================================= */

function formatPrice(price) {

    return new Intl.NumberFormat(
        "en-US",
        {
            style: "currency",
            currency: "EUR"
        }
    ).format(price);

}



/* =========================================
   CART COUNT
========================================= */

function updateCartCount() {

    if (!cartCount) {
        return;
    }


    cartCount.textContent =
        cart.length;

}



/* =========================================
   RENDER CATEGORY PAGE
========================================= */

function renderCategory() {

    if (!artGrid) {
        return;
    }


    const category =
        document.body.dataset.category;


    if (!category) {
        return;
    }


    const results =
        artworks.filter(
            artwork =>
                artwork.category ===
                category
        );


    artGrid.innerHTML = "";


    results.forEach(
        artwork => {


            const card =
                document.createElement(
                    "article"
                );


            card.className =
                "art-card";


            const favorite =
                favorites.includes(
                    artwork.name
                );


            card.innerHTML = `

                <div class="image-container">

                    <img
                        src="image/${artwork.file}"
                        alt="${artwork.name}"
                        loading="lazy"
                    >

                    <button
                        class="heart ${favorite ? "active" : ""}"
                        type="button"
                        data-name="${artwork.name}"
                    >
                        ${favorite ? "♥" : "♡"}
                    </button>

                </div>


                <div class="art-details">

                    <h3>
                        ${artwork.name}
                    </h3>


                    <p>
                        Original artwork by Parisa
                    </p>


                    <div class="art-bottom">

                        <strong>
                            ${formatPrice(artwork.price)}
                        </strong>


                        <button
                            class="add-cart"
                            type="button"
                            data-name="${artwork.name}"
                        >
                            Add to Cart
                        </button>

                    </div>

                </div>

            `;


            artGrid.appendChild(
                card
            );

        }
    );

}



/* =========================================
   FIND ARTWORK
========================================= */

function findArtwork(name) {

    return artworks.find(
        artwork =>
            artwork.name === name
    );

}



/* =========================================
   ADD TO CART
========================================= */

function addToCart(
    name,
    button
) {

    const artwork =
        findArtwork(name);


    if (!artwork) {
        return;
    }


    const exists =
        cart.some(
            item =>
                item.name ===
                artwork.name
        );


    if (exists) {

        button.textContent =
            "Already in Cart";


        setTimeout(
            () => {

                button.textContent =
                    "Add to Cart";

            },
            1200
        );


        return;
    }


    cart.push({

        name:
            artwork.name,

        price:
            artwork.price,

        file:
            artwork.file

    });


    localStorage.setItem(
        "parisaCart",
        JSON.stringify(cart)
    );


    updateCartCount();


    button.textContent =
        "Added ✓";


    setTimeout(
        () => {

            button.textContent =
                "Add to Cart";

        },
        1200
    );

}



/* =========================================
   FAVORITE
========================================= */

function toggleFavorite(name) {

    if (
        favorites.includes(name)
    ) {

        favorites =
            favorites.filter(
                item =>
                    item !== name
            );

    } else {

        favorites.push(name);

    }


    localStorage.setItem(
        "parisaFavorites",
        JSON.stringify(
            favorites
        )
    );


    renderCategory();

}



/* =========================================
   PRODUCT CLICKS
========================================= */

if (artGrid) {

    artGrid.addEventListener(
        "click",
        event => {


            const cartButton =
                event.target.closest(
                    ".add-cart"
                );


            if (cartButton) {

                addToCart(
                    cartButton.dataset.name,
                    cartButton
                );


                return;
            }


            const heartButton =
                event.target.closest(
                    ".heart"
                );


            if (heartButton) {

                toggleFavorite(
                    heartButton.dataset.name
                );

            }

        }
    );

}



/* =========================================
   START
========================================= */

updateCartCount();

renderCategory();